import re
import subprocess
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any

from grpc_tools import protoc
from hatchling.builders.hooks.plugin.interface import BuildHookInterface
from typing_extensions import Self


@dataclass
class Files:
    proto_path: Path
    proto_files: list[Path]
    output_path: Path
    output_files: list[Path]

    def from_config(config: dict[str, Any]) -> Self | None:
        proto_path = Path(config["proto_path"])
        if not proto_path.is_dir():
            return None
        proto_files = [path for path in proto_path.rglob("*.proto")]

        output_path = Path(config["output_path"])
        output_files = [
            output_path / file.relative_to(proto_path).with_name(file.stem + suffix)
            for file in proto_files
            for suffix in ["_pb2.py", "_pb2.pyi"]
        ]

        return Files(proto_path, proto_files, output_path, output_files)


class CustomBuildHook(BuildHookInterface):
    def initialize(self, version: str, build_data: dict[str, Any]) -> None:
        self.generate_api_version(build_data)
        self.generate_protobuf(build_data)

    def clean(self, versions: list[str]) -> None:
        generated_files = [Path("kipy/kicad_api_version.py")]
        files = Files.from_config(self.config)
        if files is not None:
            generated_files += files.output_files

        for file in generated_files:
            if file.is_file():
                self.app.display_info(f"Deleting {file}")
                file.unlink(missing_ok=True)

    def generate_api_version(self, build_data: dict[str, Any]) -> None:
        if not Path("kicad").is_dir():
            return None

        try:
            git_version = subprocess.check_output(
                ["git", "describe", "--long", "--always"],
                cwd="kicad",
                text=True,
            ).strip()
        except subprocess.CalledProcessError:
            git_version = "unknown"

        version_file = Path("kipy/kicad_api_version.py")
        with open(version_file, "w") as file:
            file.write("# This file is automatically generated, do not modify it\n")
            file.write(f'KICAD_API_VERSION = "{git_version}"\n')

        build_data["artifacts"] += [version_file.as_posix()]

    def generate_protobuf(self, build_data: dict[str, Any]) -> None:
        files = Files.from_config(self.config)
        if files is None:
            return None

        self.app.display_info("Generating protobuf bindings...")
        internal_protos = (resources.files("grpc_tools") / "_proto").resolve()
        protoc.main(
            [
                "protoc",
                f"--proto_path={internal_protos}",
                f"--proto_path={files.proto_path}",
                f"--python_out={files.output_path}",
                f"--mypy_out={files.output_path}",
                *[str(file) for file in files.proto_files],
            ]
        )

        packages = [path.name for path in files.output_path.iterdir() if path.is_dir()]
        pattern = re.compile(
            rf"^(from\s+)({'|'.join(re.escape(p) for p in packages)}\b)", re.MULTILINE
        )

        for file in files.output_files:
            depth = len(file.parent.relative_to(files.output_path).parts)
            dots = "." * (depth + 1)

            content = file.read_text(encoding="utf-8")
            new_content = pattern.sub(rf"\g<1>{dots}\g<2>", content)

            if new_content != content:
                file.write_text(new_content, encoding="utf-8")

        build_data["artifacts"] += [file.as_posix() for file in files.output_files]
